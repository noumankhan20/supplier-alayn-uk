export type OrderTab = "TODO" | "ON_THE_WAY" | "DONE" | "ALL";

/** Waiting on the supplier: pack it or send it. */
export const needsAction = (s: OrderStatus) => s === "SENT" || s === "PACKING";

export function tabOf(s: OrderStatus): Exclude<OrderTab, "ALL"> {
  if (needsAction(s)) return "TODO";
  if (s === "DISPATCHED" || s === "PARTIALLY_DISPATCHED") return "ON_THE_WAY";
  return "DONE";
}

/**
 * The order number the restaurant and Alayn notifications also use, e.g. "PO-SEA-20261102-001".
 * Generated by the backend (alayn-backend src/utils/poNumber.ts).
 */
export function formatOrderNo(po: { poNumber?: string | null }): string {
  return po.poNumber || "Order";
}

/** "Just now", "25 min ago", "3 h ago", "Yesterday", or a date. Safe for Next.js prerender. */
export function timeAgo(iso?: string, now?: number | null): string {
  if (!iso) return "";
  const then = new Date(iso);
  if (!now) {
    return then.toLocaleDateString("en-IN", { day: "numeric", month: "short" });
  }
  const mins = Math.round((now - then.getTime()) / 60000);
  if (mins < 1) return "Just now";
  if (mins < 60) return `${mins} min ago`;
  const hours = Math.round(mins / 60);
  if (hours < 24) return `${hours} h ago`;
  if (hours < 48) return "Yesterday";
  return then.toLocaleDateString("en-IN", { day: "numeric", month: "short" });
}

export function formatDate(iso?: string): string {
  if (!iso) return "";
  return new Date(iso).toLocaleDateString("en-IN", { day: "numeric", month: "short", year: "numeric" });
}
